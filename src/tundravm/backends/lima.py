"""Builds inside a Lima VM: an x86-64 Debian guest running the same pinned mkosi.

For hosts that cannot build natively (macOS, non-x86-64 Linux). The guest is always
x86-64 (``arch: x86_64``, ``vmType: qemu``) and gets mkosi :data:`~tundravm.toolchain.MKOSI_PIN`
(the same git commit tundravm depends on) in a virtualenv, so a Lima build runs the mkosi
and the tools tree a Linux build runs, and produces the same bytes.

The cost on Apple Silicon: QEMU emulates the x86-64 guest with TCG, instruction by
instruction, so a build takes several times longer than on an x86-64 host (an Intel Mac or
Linux host accelerates the same guest with HVF/KVM). The faster options (an arm64 guest
cross-building, or Rosetta) change the bytes or cannot be made reproducible, so they are not
offered.

mkosi runs in the guest as the ``debian`` user (Debian kernels allow unprivileged user
namespaces); its cache, tools tree and output live on the guest's disk and the output is
moved to the host's build directory, which the guest mounts at ``/home/debian/mnt``.
"""

from __future__ import annotations

import hashlib
import json
import shlex
import shutil
import subprocess
import textwrap
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import NoReturn

from tundravm.backends.base import (
    MountSpec,
    Requirement,
    StreamResult,
    build_sources_args,
    collect_artifacts,
    failure_message,
    mkosi_project,
    run_streaming,
)
from tundravm.backends.local_linux import SUMMARY_FILENAME
from tundravm.errors import BackendExecutionError
from tundravm.models import BakeRequest, BakeResult, ProfileBuildResult
from tundravm.toolchain import MKOSI_PIN, MkosiTool, ToolsTree, pinned_mkosi

VM_MKOSI_VENV = f"/opt/tundravm/mkosi-{MKOSI_PIN.commit[:12]}"
"""The guest virtualenv holding the pinned mkosi; a new pin gets a new one."""
VM_MKOSI = f"{VM_MKOSI_VENV}/bin/mkosi"

INSTALL_MKOSI = (
    f"test -x {VM_MKOSI} || {{ python3 -m venv {VM_MKOSI_VENV} && "
    f"{VM_MKOSI_VENV}/bin/pip install --quiet {shlex.quote(MKOSI_PIN.requirement)}; }}"
)
"""Install the pinned mkosi into the guest unless it is there (provisioning and every build)."""

GUEST_PACKAGES = ("python3", "python3-venv", "git", "sudo", "debian-archive-keyring", "uidmap")
"""What the guest needs besides mkosi: Python for mkosi, git for pip, the Debian keyring."""

LIMA_YAML_TEMPLATE = textwrap.dedent("""\
    # Generated by tundravm: an x86-64 Debian guest with mkosi {mkosi_version}.
    # On Apple Silicon QEMU emulates it (TCG): identical bytes, several times slower.
    vmType: qemu
    arch: x86_64
    images:
      - location: "https://cloud.debian.org/images/cloud/trixie/latest/debian-13-genericcloud-amd64.qcow2"
        arch: "x86_64"
    cpus: {cpus}
    memory: "{memory}"
    disk: "{disk}"
    user:
      name: debian
      uid: 1000
      home: /home/debian
    containerd:
      user: false
    mountTypesUnsupported: [9p]
    mounts:
      - location: "{mount_source}"
        mountPoint: /home/debian/mnt
        writable: true
    ssh:
      forwardAgent: true
    provision:
      - mode: system
        script: |
          #!/bin/bash
          set -euo pipefail
          apt-get update
          apt-get install -y {packages}
          echo "debian ALL=(ALL) NOPASSWD:ALL" > /etc/sudoers.d/debian
          mkdir -p /opt/tundravm
          chown debian: /opt/tundravm
      - mode: user
        script: |
          #!/bin/bash
          set -euo pipefail
          {install_mkosi}
""")


def lima_yaml(backend: LimaMkosiBackend, mount_source: str) -> str:
    """The Lima VM config for *backend*, mounting *mount_source*."""
    return LIMA_YAML_TEMPLATE.format(
        mkosi_version=MKOSI_PIN.version,
        cpus=backend.cpus,
        memory=backend.memory,
        disk=backend.disk,
        mount_source=mount_source,
        packages=" ".join(GUEST_PACKAGES),
        install_mkosi=INSTALL_MKOSI,
    )


VM_MOUNT = "/home/debian/mnt"
"""Where the VM sees the host build directory."""

MKOSI_STATE_DIR = "/home/debian/mkosi-state"
"""Where mkosi runs in the guest: its workspace and the default tools tree (reused)."""
MKOSI_CACHE_DIR = "/home/debian/mkosi-cache"
MKOSI_OUTPUT_DIR = "/home/debian/mkosi-output"


@dataclass(slots=True)
class LimaMkosiBackend:
    """Run the pinned mkosi in an x86-64 Debian Lima guest (see the module docstring)."""

    cpus: int = field(repr=True)
    memory: str = field(repr=True)
    disk: str = field(repr=True)
    name: str = "lima_mkosi"
    instance_name: str | None = None
    mkosi_args: list[str] = field(default_factory=list)
    tools_tree: ToolsTree | None = field(default=None, init=False, repr=False, compare=False)
    """The tools tree the last build resolved in the guest (``mkosi summary --json``)."""
    _last_instance: str | None = field(init=False, default=None, repr=False)

    @property
    def mkosi_tool(self) -> MkosiTool:
        """The mkosi the guest runs: the pinned commit."""
        return pinned_mkosi()

    def requirements(self) -> tuple[Requirement, ...]:
        return (
            Requirement(
                tool="limactl",
                probe=("limactl", "--version"),
                hint="Install Lima: https://lima-vm.io/docs/installation/",
            ),
        )

    def fingerprint(self) -> dict[str, object]:
        """The backend name, the VM's size and instance, the extra mkosi arguments and mkosi."""
        return {
            "name": self.name,
            "cpus": self.cpus,
            "memory": self.memory,
            "disk": self.disk,
            "instance": self.instance_name,
            "mkosi_args": list(self.mkosi_args),
            "mkosi": self.mkosi_tool.label(),
        }

    def mount_plan(self, request: BakeRequest) -> tuple[MountSpec, ...]:
        """Single mount: build_dir -> /home/debian/mnt."""
        return (MountSpec(source=request.build_dir, target=VM_MOUNT),)

    def prepare(self, request: BakeRequest) -> None:
        self._ensure_lima_available()
        request.build_dir.mkdir(parents=True, exist_ok=True)
        request.emit_dir.mkdir(parents=True, exist_ok=True)

        instance = self._resolve_instance_name(request)
        self._last_instance = instance

        if not self._instance_running(instance):
            self._start_instance(instance, request)

    def execute(self, request: BakeRequest) -> BakeResult:
        self._ensure_lima_available()
        instance = self._resolve_instance_name(request)
        context = {
            "backend": self.name,
            "operation": "execute",
            "profile": request.profile,
            "instance": instance,
        }

        dirs = " ".join((MKOSI_STATE_DIR, MKOSI_CACHE_DIR, MKOSI_OUTPUT_DIR))
        setup = self._lima_exec(instance, f"mkdir -p {dirs} && {INSTALL_MKOSI}")
        if setup.returncode != 0:
            raise BackendExecutionError(
                f"Could not install mkosi {MKOSI_PIN.version} in the Lima VM: "
                f"{_last_line(setup.stderr) or 'exit ' + str(setup.returncode)}.",
                hint=f"Run `limactl shell {instance}` and check the guest's network.",
                context=context,
            )
        self._check_mkosi_version(instance, context)

        args = self._mkosi_args(request)
        summary = self._lima_exec(
            instance, self._in_state([*args, "--no-pager", "summary", "--json"])
        )
        try:
            resolved = json.loads(summary.stdout or "")
        except ValueError:
            raise BackendExecutionError(
                "mkosi summary --json failed inside the Lima VM: "
                f"{_last_line(summary.stderr) or 'no output'}.",
                hint="The mkosi tree does not parse; run the same summary on a Linux host "
                "to see mkosi's complaint.",
                context=context,
            ) from None
        self.tools_tree = ToolsTree.from_summary(resolved.get("Tools"))
        profile_dir = request.build_dir.resolve() / request.profile
        profile_dir.mkdir(parents=True, exist_ok=True)
        (profile_dir / SUMMARY_FILENAME).write_text(
            json.dumps(resolved, indent=2) + "\n", encoding="utf-8"
        )

        result = run_streaming(
            self._ssh_argv(instance, self._in_state([*args, "build"])),
            on_output=request.on_output,
        )
        if result.returncode != 0:
            raise BackendExecutionError(
                failure_message(
                    "mkosi build failed inside Lima VM.",
                    result,
                    streamed=request.on_output is not None,
                ),
                hint="Check Lima VM status with `limactl list` and mkosi output for details.",
                context={**context, "returncode": str(result.returncode)},
            )

        output_dir = profile_dir / "output"
        host_output = shlex.quote(self._vm_path(request, output_dir))
        self._lima_exec(
            instance,
            f"mkdir -p {host_output} && mv {MKOSI_OUTPUT_DIR}/* {host_output}/ 2>/dev/null || true",
        )

        profile_result = ProfileBuildResult(profile=request.profile)
        profile_result.artifacts = collect_artifacts(output_dir, request.output_targets)
        return BakeResult(profiles={request.profile: profile_result})

    def cleanup(self, request: BakeRequest) -> None:
        pass

    def stop(self, instance: str | None = None) -> None:
        """Stop a Lima instance. Uses last-used instance if not specified."""
        if shutil.which("limactl") is None:
            return
        target = instance or self._last_instance
        if target is None:
            return
        subprocess.run(["limactl", "stop", target], capture_output=True, check=False)

    def _resolve_instance_name(self, request: BakeRequest) -> str:
        """Generate a unique VM name from the emit_dir path, or use override."""
        if self.instance_name is not None:
            return self.instance_name
        h = hashlib.sha256(str(request.emit_dir.resolve()).encode()).hexdigest()[:8]
        return f"tdx-builder-{h}"

    def _mkosi_args(self, request: BakeRequest) -> list[str]:
        """mkosi's arguments inside the VM, before the verb (absolute guest paths): only
        paths and the selection (``request.mkosi_args``); the tree carries every setting."""
        mkosi_dir = mkosi_project(request.emit_dir.resolve())
        args = [
            f"--directory={self._vm_path(request, mkosi_dir)}",
            "--force",
            f"--cache-directory={MKOSI_CACHE_DIR}",
            f"--output-directory={MKOSI_OUTPUT_DIR}",
        ]
        if request.sources_dir is not None:
            # under the build directory, so the VM sees it through the same mount
            args.extend(
                build_sources_args(
                    mkosi_dir,
                    sources=self._vm_path(request, request.sources_dir),
                    config_dir=self._vm_path(request, mkosi_dir),
                    mkosi_args=self.mkosi_args,
                )
            )
        args.extend(request.mkosi_args)
        args.extend(self.mkosi_args)
        return args

    @staticmethod
    def _in_state(args: list[str]) -> str:
        """``cd`` to the guest state directory and run the pinned mkosi with *args*."""
        command = " ".join(shlex.quote(arg) for arg in [VM_MKOSI, *args])
        return f"cd {MKOSI_STATE_DIR} && {command}"

    def _check_mkosi_version(self, instance: str, context: dict[str, str]) -> None:
        probe = self._lima_exec(instance, f"{VM_MKOSI} --version")
        words = (probe.stdout or "").split()
        if probe.returncode != 0 or MKOSI_PIN.version not in words:
            found = (probe.stdout or probe.stderr or "nothing").strip()
            raise BackendExecutionError(
                f"The Lima VM's {VM_MKOSI} is not mkosi {MKOSI_PIN.version}: {found}.",
                hint=f"Remove {VM_MKOSI_VENV} in the VM (`limactl shell {instance}`) "
                "and bake again to reinstall it.",
                context=context,
            )

    def _vm_path(self, request: BakeRequest, host: Path) -> str:
        """*host* (under the build directory) as the VM sees it through the mount."""
        build_dir = request.build_dir.resolve()
        try:
            relative = host.resolve().relative_to(build_dir)
        except ValueError:
            raise BackendExecutionError(
                f"{host} is outside the build directory the Lima VM mounts.",
                hint=f"Keep the mkosi tree and output under {build_dir}.",
                context={"backend": self.name, "operation": "execute", "path": str(host)},
            ) from None
        return str(PurePosixPath(VM_MOUNT, *relative.parts))

    def _lima_exec(self, instance: str, cmd: str) -> subprocess.CompletedProcess[str]:
        """Execute a short command inside the Lima VM via SSH, capturing its output."""
        return subprocess.run(
            self._ssh_argv(instance, cmd), capture_output=True, text=True, check=False
        )

    @staticmethod
    def _ssh_argv(instance: str, cmd: str) -> list[str]:
        ssh_config = Path.home() / ".lima" / instance / "ssh.config"
        return [
            "ssh",
            "-F",
            str(ssh_config),
            f"lima-{instance}",
            "-o",
            "LogLevel=QUIET",
            "--",
            "bash",
            "-c",
            cmd,
        ]

    def _instance_running(self, instance: str) -> bool:
        """Check if a Lima instance exists and is running."""
        status = self._instance_status(instance)
        return status == "Running"

    def _instance_exists(self, instance: str) -> bool:
        """Check if a Lima instance exists (running or stopped)."""
        return self._instance_status(instance) is not None

    def _instance_status(self, instance: str) -> str | None:
        result = subprocess.run(
            ["limactl", "list", "--json"], capture_output=True, text=True, check=False
        )
        if result.returncode != 0:
            return None
        try:
            for line in result.stdout.strip().splitlines():
                data = json.loads(line)
                if data.get("name") == instance:
                    return str(data.get("status"))
        except (json.JSONDecodeError, KeyError):
            pass
        return None

    def _start_instance(self, instance: str, request: BakeRequest) -> None:
        """Create and start a Lima instance."""
        mount_source = str(request.build_dir.resolve())
        config_path = request.build_dir / "lima.yaml"
        config_path.parent.mkdir(parents=True, exist_ok=True)
        config_path.write_text(lima_yaml(self, mount_source), encoding="utf-8")

        if not self._instance_exists(instance):
            argv = ["limactl", "create", "-y", "--name", instance, str(config_path)]
            result = run_streaming(argv, on_output=request.on_output)
            if result.returncode != 0:
                message = "Failed to create Lima VM instance."
                self._raise_instance_error(message, "create_instance", instance, result, request)

        result = run_streaming(["limactl", "start", "-y", instance], on_output=request.on_output)
        if result.returncode != 0:
            self._raise_instance_error(
                "Failed to start Lima VM instance.", "start_instance", instance, result, request
            )

    def _raise_instance_error(
        self,
        message: str,
        operation: str,
        instance: str,
        result: StreamResult,
        request: BakeRequest,
    ) -> NoReturn:
        raise BackendExecutionError(
            failure_message(message, result, streamed=request.on_output is not None),
            hint="Check Lima installation and available disk space.",
            context={
                "backend": self.name,
                "operation": operation,
                "instance": instance,
                "returncode": str(result.returncode),
            },
        )

    def _ensure_lima_available(self) -> None:
        if shutil.which("limactl") is None:
            raise BackendExecutionError(
                "Lima backend requires `limactl` in PATH.",
                hint="Install Lima: https://lima-vm.io/docs/installation/",
                context={"backend": self.name, "operation": "prepare"},
            )


def _last_line(text: str | None) -> str:
    lines = (text or "").strip().splitlines()
    return lines[-1] if lines else ""
